// Glyphs are 5x7 bitmaps, with the most significant bit on the left.

export const GLYPH_WIDTH = 5;
export const GLYPH_HEIGHT = 7;

/** How the orbs move once the grid is laid out. */
export type DotMotion = "reveal" | "wave" | "scan" | "still";

export type DotGrid = {
	cols: number;
	rows: number;
	/** `cells[row][column]` is true when the orb is part of the mark. */
	cells: readonly (readonly boolean[])[];
};

