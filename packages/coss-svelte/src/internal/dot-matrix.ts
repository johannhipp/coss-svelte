const glyphRows = (character: string): readonly number[] => GLYPHS[character] ?? MISSING_GLYPH;

const bitAt = (row: number, column: number): boolean =>
	(row & (1 << (GLYPH_WIDTH - 1 - column))) !== 0;

/**
 * Lays text out as a dot grid. Lowercase letters are folded to uppercase, `\n`
 * starts a new line, and unsupported characters render as a hollow box.
 */
export function dotMatrixGrid(text: string, letterGap = 1, lineGap = 1): DotGrid {
	const lines = text.split("\n").map((line) => [...line.toUpperCase()].map(glyphRows));
	if (lines.every((glyphs) => glyphs.length === 0)) return { cols: 0, rows: 0, cells: [] };

	const cols = Math.max(
		...lines.map(
			(glyphs) => glyphs.length * GLYPH_WIDTH + Math.max(0, glyphs.length - 1) * letterGap
		)
	);
	const rows = lines.length * GLYPH_HEIGHT + (lines.length - 1) * lineGap;
	const cells = Array.from({ length: rows }, () => Array.from({ length: cols }, () => false));

	lines.forEach((glyphs, line) => {
		const top = line * (GLYPH_HEIGHT + lineGap);
		glyphs.forEach((glyph, index) => {
			const left = index * (GLYPH_WIDTH + letterGap);
			glyph.forEach((bits, y) => {
				const row = cells[top + y];
				if (row) for (let x = 0; x < GLYPH_WIDTH; x += 1) row[left + x] = bitAt(bits, x);
			});
		});
	});

	return { cols, rows, cells };
}
